import { readdirSync, readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import path from 'node:path';

/**
 * Writes src/db/migrations.gen.ts from the SQL that drizzle-kit generated.
 * The Worker cannot read files at run time, so the migrations travel inside
 * the bundle. `npm run db:generate` runs this after drizzle-kit; a test fails
 * if the two ever drift.
 */
const here = path.dirname(fileURLToPath(import.meta.url));
const dir = path.resolve(here, '../migrations');

export function renderMigrations(): string {
  const files = readdirSync(dir).filter((f) => f.endsWith('.sql')).sort();
  const entries = files.map((f) => ({ tag: f.replace(/\.sql$/, ''), sql: readFileSync(path.join(dir, f), 'utf8') }));
  return `/* Generated by scripts/bundle-migrations.ts from migrations/*.sql. Do not edit. */\n\nexport const MIGRATIONS: ReadonlyArray<{ tag: string; sql: string }> = ${JSON.stringify(entries, null, 2)};\n`;
}

if (process.argv[1] && fileURLToPath(import.meta.url) === path.resolve(process.argv[1])) {
  writeFileSync(path.resolve(here, '../src/db/migrations.gen.ts'), renderMigrations());
  console.log('migrations bundled');
}
